"""``STUDENT_T_QUANTILES[p][df - 1]`` : le quantile ``p`` de Student à ``df``
degrés de liberté."""


def student_t_quantile(p: float, df: int) -> float:
    """Le quantile ``p`` (0,975 ou 0,80) de Student à ``df`` degrés de liberté
    (``df`` >= 1) : la table jusqu'à 100, la loi normale au-delà ; ``ValueError``
    pour un autre ``p`` ou ``df`` < 1."""
    if p not in STUDENT_T_QUANTILES:
        raise ValueError(f"student_t_quantile : p vaut 0.975 ou 0.8, reçu {p!r}.")
    if isinstance(df, bool) or not isinstance(df, int) or df < 1:
        raise ValueError(f"student_t_quantile : df entier >= 1 attendu, reçu {df!r}.")
    if df <= len(STUDENT_T_QUANTILES[p]):
        return STUDENT_T_QUANTILES[p][df - 1]
    return NormalDist().inv_cdf(p)
